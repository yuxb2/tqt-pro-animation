G['\x07'] = G['*d']    # bullet
G['\xb0'] = G['~']     # degree

ORDER = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,-+/:;'\"!?*=#()\x07\xb0"

def emit_c():
    """Emit the C table: int8 stream, -128 ends a polyline, -127 ends the glyph."""
    out = []
    strokes = []
    offs = {}
    for ch in ORDER:
        offs[ch] = len(strokes)
        for pl in G[ch]:
            for (x, y) in pl:
                strokes += [x, y]
            strokes.append(-128)
        strokes.append(-127)
    return ORDER, offs, strokes
