POLYGONS = [AFRICA, EURASIA, NAMERICA, SAMERICA, AUSTRALIA, GREENLAND, ANTARCTIC_PEN,
            MADAGASCAR, BRITAIN, IRELAND, JAPAN, NEWZEALAND, SUMATRA, JAVA, BORNEO,
            NEWGUINEA, PHILIPPINES, SULAWESI]

ANTARCTICA_LAT = -70.0   # everything south of this is land


def build_mask(lon_n=LON_N, lat_n=LAT_N):
    """Returns a list of bytearrays: mask[row][col] = 1 for land."""
    mask = [bytearray(lon_n) for _ in range(lat_n)]
    for row in range(lat_n):
        lat = 90.0 - (row + 0.5) * 180.0 / lat_n
        if lat <= ANTARCTICA_LAT:
            for c in range(lon_n):
                mask[row][c] = 1
            continue
        spans = []
        for poly in POLYGONS:
            xs = []
            n = len(poly)
            for i in range(n):
                x1, y1 = poly[i]
                x2, y2 = poly[(i + 1) % n]
                if (y1 > lat) != (y2 > lat):
                    t = (lat - y1) / (y2 - y1)
                    xs.append(x1 + t * (x2 - x1))
            xs.sort()
            for i in range(0, len(xs) - 1, 2):
                spans.append((xs[i], xs[i + 1]))
        for a, b in spans:
            ca = int((a + 180.0) * lon_n / 360.0 + 0.5)
            cb = int((b + 180.0) * lon_n / 360.0 + 0.5)
            if cb < ca:
                ca, cb = cb, ca
            for c in range(max(0, ca), min(lon_n, cb)):
                mask[row][c] = 1
    return mask


